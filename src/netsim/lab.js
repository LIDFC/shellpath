/** Имя машины для приглашения и $HOSTNAME. */
export function displayHostname() {
  const h = labHost();
  if (h) return h.rt.hostname;
  return S.host || 'laptop';
}

export const macOf = (host, iface) => {
  const x = hashStr(host + ':' + iface);
  return 'bc:24:11:' + [(x >>> 16) & 255, (x >>> 8) & 255, x & 255].map((v) => v.toString(16).padStart(2, '0')).join(':');
};

const iptablesFile = (rules) =>
  `# Generated by iptables-save v1.8.10\n*nat\n:PREROUTING ACCEPT [0:0]\n:INPUT ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\n:POSTROUTING ACCEPT [0:0]\n` +
  rules.map((r) => r + '\n').join('') +
  'COMMIT\n*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\nCOMMIT\n';

/** Собрать файловую систему машины так, как её настроил бы администратор. */
function makeLabHost(id, sp) {
  const fs = D();
  const P = (p, n) => put(p, n, fs);
  for (const n of ['bin', 'etc', 'root', 'tmp', 'usr', 'var', 'proc']) fs.c[n] = D();
  fs.c.root.m = 0o700;
  fs.c.tmp.m = 0o1777;
  P('/etc/os-release', F(`NAME="ALT Server"\nVERSION="10.4"\nID=altlinux\nVERSION_ID=10.4\nPRETTY_NAME="${OSNAME}"\nHOME_URL="https://basealt.ru/"\n`));
  P('/etc/hostname', F(sp.hostname + '\n'));
  P('/etc/hosts', F('127.0.0.1\tlocalhost.localdomain localhost\n::1\tlocalhost6.localdomain6 localhost6\n'));
  P('/etc/resolv.conf', F(''));
  P('/etc/sysctl.conf', F('# Параметры ядра, применяются при загрузке\n# Синтаксис: параметр = значение\n'));
  P('/etc/net/sysctl.conf', F(`# Параметры ядра, которые etcnet применяет при запуске сети\nnet.ipv4.ip_forward = ${sp.fwd ? 1 : 0}\nnet.ipv4.conf.default.rp_filter = 1\nnet.ipv4.tcp_syncookies = 1\n`));
  P('/etc/net/ifaces/lo/options', F('TYPE=eth\nBOOTPROTO=static\nDISABLED=no\n'));
  P('/etc/net/ifaces/lo/ipv4address', F('127.0.0.1/8\n'));
  P('/etc/net/ifaces/default/options', F('# Значения по умолчанию для всех интерфейсов\nBOOTPROTO=static\nCONFIG_IPV4=yes\nDISABLED=no\nONBOOT=yes\n'));
  const phys = [];
  for (const f of sp.ifaces) {
    if (!f.tun) phys.push({ n: f.n, seg: f.seg, mac: macOf(id, f.n) });
    if (f.noconf) continue;
    const d = '/etc/net/ifaces/' + f.n;
    let o = f.tun
      ? `TYPE=iptun\nTUNTYPE=gre\nTUNLOCAL=${f.tun.local}\nTUNREMOTE=${f.tun.remote}\nTUNOPTIONS='ttl 64'\nHOST=ens18\n`
      : 'TYPE=eth\n';
    o += 'DISABLED=no\nBOOTPROTO=static\nCONFIG_IPV4=yes\n';
    P(d + '/options', F(o));
    if (f.addr) P(d + '/ipv4address', F(f.addr.join('\n') + '\n'));
    if (f.route) P(d + '/ipv4route', F(f.route.join('\n') + '\n'));
    if (f.dns) P(d + '/resolv.conf', F(f.dns.join('\n') + '\n'));
  }
  if (sp.nat) P('/etc/sysconfig/iptables', F(iptablesFile(sp.nat), 'root', 'root', 0o600));
  return { id, fs, phys, svc: { network: true, sshd: true, iptables: !!sp.nat }, svcA: {}, rt: null };
}

/* ---------- параметры ядра ---------- */
export const SYSCTL_DEFAULTS = {
  'net.ipv4.ip_forward': '0',
  'net.ipv4.conf.all.forwarding': '0',
  'net.ipv4.conf.default.rp_filter': '1',
  'net.ipv4.conf.all.rp_filter': '1',
  'net.ipv4.tcp_syncookies': '1',
  'net.ipv4.icmp_echo_ignore_all': '0',
  'net.ipv6.conf.all.disable_ipv6': '0',
  'kernel.hostname': '',
};
const isForward = (k) => k === 'net.ipv4.ip_forward' || k === 'net.ipv4.conf.all.forwarding';

export function getSys(h, k) {
  if (isForward(k)) return h.rt.fwd ? '1' : '0';
  if (k === 'kernel.hostname') return h.rt.hostname;
  return h.rt.sys[k];
}

/** Установить параметр. Возвращает текст ошибки или ''. */
export function setSys(h, k, v) {
  k = k.replace(/\//g, '.');
  if (!(k in SYSCTL_DEFAULTS)) return `sysctl: cannot stat /proc/sys/${k.replace(/\./g, '/')}: No such file or directory`;
  if (k === 'kernel.hostname') {
    h.rt.hostname = v;
    return '';
  }
  if (!/^\d+$/.test(v)) return `sysctl: setting key "${k}": Invalid argument`;
  if (isForward(k)) {
    h.rt.fwd = +v > 0;
    return '';
  }
  h.rt.sys[k] = v;
  return '';
}

/** Применить файл вида «параметр = значение». Ошибки и (при verbose) применённые строки — в out. */
export function applySysctl(h, text, out, verbose, file) {
  lines(text || '').forEach((raw, i) => {
    const l = raw.replace(/[#;].*$/, '').trim();
    if (!l) return;
    const m = /^([\w.\-/]+)\s*=\s*(.*)$/.exec(l);
    if (!m) {
      out.push(`sysctl: ${file || '-'}(${i + 1}): invalid syntax, continuing...`);
      return;
    }
    const e = setSys(h, m[1], m[2].trim());
    if (e) out.push(e);
    else if (verbose) out.push(`${m[1].replace(/\//g, '.')} = ${m[2].trim()}`);
  });
}

/* ---------- состояние интерфейсов и маршруты ---------- */
function freshRuntime(h) {
  const rt = {
    links: { lo: { up: true } },
    addrs: { lo: [{ ip: '127.0.0.1', p: 8 }] },
    tun: {},
    routes: [],
    fwd: false,
    sys: { ...SYSCTL_DEFAULTS },
    hostname: 'localhost',
    ipt: emptyTables(),
  };
  for (const p of h.phys) {
    rt.links[p.n] = { up: false };
    rt.addrs[p.n] = [];
  }
  return rt;
}

export const parseOpts = (t) => {
  const o = {};
  for (const raw of lines(t || '')) {
    const m = /^([A-Z0-9_]+)\s*=\s*(.*)$/.exec(raw.replace(/#.*$/, '').trim());
    if (m) o[m[1]] = m[2].trim().replace(/^(['"])(.*)\1$/, '$2');
  }
  return o;
};

export const firstAddr = (h, dev) => (h.rt.addrs[dev] || [])[0]?.ip || null;
export const ownAddr = (h, ip) =>
  Object.values(h.rt.addrs).some((a) => a.some((x) => x.ip === ip)) || (ip2n(ip) !== null && inNet(ip, '127.0.0.0', 8));
const hasCarrier = (h, dev) => {
  if (dev === 'lo' || h.rt.tun[dev]) return true;
  const p = h.phys.find((x) => x.n === dev);
  return !!(p && p.seg);
};

/** Маршруты в подключённые сети (их ядро создаёт само из адресов интерфейсов). */
export function connectedRoutes(h) {
  const r = [];
  for (const [dev, list] of Object.entries(h.rt.addrs)) {
    if (dev === 'lo' || !h.rt.links[dev]?.up || !hasCarrier(h, dev)) continue;
    for (const a of list) {
      if (a.p >= 32) continue;
      const net = netOf(a.ip, a.p);
      if (!r.some((x) => x.dev === dev && x.net === net && x.p === a.p)) r.push({ net, p: a.p, dev, src: a.ip, k: 1 });
    }
  }
  return r;
}

/** Самый длинный подходящий префикс. */
export function lookupRoute(h, dst) {
  const c = [...connectedRoutes(h), ...h.rt.routes.filter((r) => h.rt.links[r.dev]?.up && hasCarrier(h, r.dev))].filter((r) => inNet(dst, r.net, r.p));
  if (!c.length) return null;
  c.sort((a, b) => b.p - a.p || (b.k || 0) - (a.k || 0));
  const b = c[0];
  return { dev: b.dev, via: b.via || null, src: b.src || firstAddr(h, b.dev), k: b.k };
}

/** «default via X dev Y» → { dst, via, dev } | { err } */
export function parseRouteArgs(t) {
  const r = {};
  let i = 0;
  if (!t.length) return { err: 'Error: missing destination' };
  r.dst = t[i++];
  if (r.dst === 'to') r.dst = t[i++];
  while (i < t.length) {
    const k = t[i++];
    const v = t[i++];
    if (k === 'via') r.via = v;
    else if (k === 'dev') r.dev = (v || '').split('@')[0];
    else if (['metric', 'proto', 'scope', 'src', 'onlink'].includes(k)) {
      /* не влияют на модель */
    } else return { err: `Error: either "to" is duplicate, or "${k}" is a garbage.` };
  }
  return r;
}

/** Добавить маршрут. Возвращает текст ошибки или ''. */
export function routeAdd(h, { dst, via, dev }, replace) {
  let net;
  if (dst === 'default') net = { ip: '0.0.0.0', p: 0 };
  else {
    net = parseCidr(dst, 32);
    if (!net) return `Error: any valid prefix is expected rather than "${dst}".`;
    if (netOf(net.ip, net.p) !== net.ip) return 'Error: Invalid prefix for given prefix length.';
  }
  if (dev && !h.rt.links[dev]) return `Cannot find device "${dev}"`;
  if (via) {
    if (ip2n(via) === null) return `Error: inet address is expected rather than "${via}".`;
    const c = connectedRoutes(h).find((r) => inNet(via, r.net, r.p) && (!dev || r.dev === dev));
    if (!c) return 'Error: Nexthop has invalid gateway.';
    dev = c.dev;
  } else if (!dev) return 'Error: Device for nexthop is not up.';
  if (!h.rt.links[dev].up) return 'Error: Device for nexthop is not up.';
  const i = h.rt.routes.findIndex((r) => r.net === net.ip && r.p === net.p);
  if (i >= 0) {
    if (!replace) return 'RTNETLINK answers: File exists';
    h.rt.routes.splice(i, 1);
  }
  h.rt.routes.push({ net: net.ip, p: net.p, via: via || null, dev });
  return '';
}

/** Выключить интерфейс: ядро удаляет маршруты через него. */
export function linkDown(h, dev) {
  h.rt.links[dev].up = false;
  h.rt.routes = h.rt.routes.filter((r) => r.dev !== dev);
}

/* ---------- etcnet ---------- */
/** systemctl restart network: перечитать /etc/net/ifaces. Проблемы — в msgs. */
export function netStart(h, msgs) {
  const rt = h.rt;
  for (const p of h.phys) {
    rt.links[p.n].up = false;
    rt.addrs[p.n] = [];
  }
  for (const n of Object.keys(rt.tun)) {
    delete rt.links[n];
    delete rt.addrs[n];
  }
  rt.tun = {};
  rt.routes = [];

  const dir = nodeIn(h.fs, '/etc/net/ifaces');
  const def = parseOpts(readIn(h.fs, '/etc/net/ifaces/default/options'));
  const names = Object.keys(dir?.c || {}).filter((n) => n !== 'default' && n !== 'lo' && dir.c[n].t === 'd');
  const conf = names.map((n) => {
    const raw = readIn(h.fs, `/etc/net/ifaces/${n}/options`);
    return { n, raw, o: { ...def, ...parseOpts(raw) } };
  });
  // Сначала обычные интерфейсы, потом туннели: туннелю нужен уже назначенный TUNLOCAL.
  const isTun = (c) => (c.o.TYPE || 'eth').toLowerCase() === 'iptun';
  conf.sort((a, b) => isTun(a) - isTun(b) || cmpName(a.n, b.n));

  const pending = [];
  const resolv = [];
  for (const { n, raw, o } of conf) {
    const base = `/etc/net/ifaces/${n}`;
    if (raw === null) {
      msgs.push(`${n}: нет файла ${base}/options, интерфейс пропущен`);
      continue;
    }
    if (/^yes$/i.test(o.DISABLED || 'no')) continue;
    const type = (o.TYPE || 'eth').toLowerCase();
    if (type === 'eth') {
      if (!rt.links[n]) {
        msgs.push(`${n}: устройство не найдено (есть: ${h.phys.map((p) => p.n).join(', ')})`);
        continue;
      }
    } else if (type === 'iptun') {
      if ((o.TUNTYPE || '').toLowerCase() !== 'gre') {
        msgs.push(`${n}: TUNTYPE=${o.TUNTYPE || '(пусто)'} — для GRE нужно TUNTYPE=gre`);
        continue;
      }
      if (ip2n(o.TUNLOCAL) === null || ip2n(o.TUNREMOTE) === null) {
        msgs.push(`${n}: TUNLOCAL и TUNREMOTE должны быть IP-адресами`);
        continue;
      }
      if (!ownAddr(h, o.TUNLOCAL)) {
        msgs.push(`${n}: адрес TUNLOCAL=${o.TUNLOCAL} не назначен ни одному интерфейсу этой машины`);
        continue;
      }
      rt.tun[n] = { local: o.TUNLOCAL, remote: o.TUNREMOTE, host: o.HOST || '' };
      rt.links[n] = { up: false };
      rt.addrs[n] = [];
    } else {
      msgs.push(`${n}: неизвестный TYPE=${o.TYPE}`);
      continue;
    }
    rt.links[n].up = true;
    const bp = (o.BOOTPROTO || 'static').toLowerCase();
    if (bp === 'dhcp') {
      msgs.push(`${n}: BOOTPROTO=dhcp — DHCP-сервер в сегменте не ответил, адрес не получен`);
      continue;
    }
    if (bp !== 'static') {
      msgs.push(`${n}: неизвестный BOOTPROTO=${o.BOOTPROTO}`);
      continue;
    }
    if (/^no$/i.test(o.CONFIG_IPV4 || 'yes')) continue;
    for (const l of lines(readIn(h.fs, base + '/ipv4address') || '')) {
      const t = l.trim();
      if (!t || t.startsWith('#')) continue;
      const c = parseCidr(t);
      if (!c) {
        msgs.push(`${n}/ipv4address: не понимаю «${t}», нужен вид 192.168.1.10/24`);
        continue;
      }
      if (!t.includes('/')) msgs.push(`${n}/ipv4address: у «${t}» нет префикса, назначено как /32`);
      if (!rt.addrs[n].some((a) => a.ip === c.ip && a.p === c.p)) rt.addrs[n].push(c);
    }
    for (const l of lines(readIn(h.fs, base + '/ipv4route') || '')) {
      const t = l.trim();
      if (t && !t.startsWith('#')) pending.push([n, t]);
    }
    for (const l of lines(readIn(h.fs, base + '/resolv.conf') || '')) if (l.trim()) resolv.push(l.trim());
  }
  for (const [n, t] of pending) {
    const r = parseRouteArgs(t.split(/\s+/));
    if (r.err) {
      msgs.push(`${n}/ipv4route «${t}»: ${r.err}`);
      continue;
    }
    const e = routeAdd(h, { ...r, dev: r.dev || n }, true);
    if (e) msgs.push(`${n}/ipv4route «${t}»: ${e}`);
  }
  applySysctl(h, readIn(h.fs, '/etc/net/sysctl.conf'), msgs, false, '/etc/net/sysctl.conf');
  // resolvconf собирает /etc/resolv.conf из resolv.conf интерфейсов
  writeIn(h.fs, '/etc/resolv.conf', '# Generated by resolvconf\n' + resolv.map((x) => x + '\n').join(''));
  h.svcA.network = true;
}

export function loadIptables(h, msgs) {
  const t = readIn(h.fs, '/etc/sysconfig/iptables');
  if (t === null) {
    msgs.push('iptables: файла /etc/sysconfig/iptables нет — загружать нечего');
    return false;
  }
  try {
    iptRestore(h.rt.ipt, t);
    return true;
  } catch (e) {
    msgs.push('iptables: ' + e);
    return false;
  }
}

/** Загрузка машины: всё, что было только в памяти, пропадает. */
export function bootHost(h, msgs = []) {
  h.rt = freshRuntime(h);
  h.rt.hostname = (readIn(h.fs, '/etc/hostname') || 'localhost').split('\n')[0].trim() || 'localhost';
  applySysctl(h, readIn(h.fs, '/etc/sysctl.conf'), msgs, false, '/etc/sysctl.conf');
  netStart(h, msgs);
  h.svcA.sshd = true;
  h.svcA.iptables = h.svc.iptables ? loadIptables(h, msgs) : false;
  return msgs;
}

export function newLab() {
  LAB.hosts = {};
  for (const [id, sp] of Object.entries(LABSPEC)) LAB.hosts[id] = makeLabHost(id, sp);
  for (const h of Object.values(LAB.hosts)) bootHost(h);
}

/* ---------- путь пакета ---------- */
function filterDrops(h, chain, pkt, inIf, outIf) {
  const tbl = h.rt.ipt.filter;
  for (const r of tbl.rules) {
    if (r.chain !== chain || !matchRule(r, pkt, inIf, outIf, inNet)) continue;
    if (r.j === 'ACCEPT') return false;
    if (r.j === 'DROP' || r.j === 'REJECT') return true;
  }
  return tbl.pol[chain] === 'DROP';
}

/** Кто в сегменте seg отвечает на адрес ip (ARP). */
function neighbor(seg, ip, except) {
  if (!seg) return null;
  for (const H of Object.values(LAB.hosts)) {
    if (H.id === except) continue;
    for (const p of H.phys) {
      if (p.seg !== seg || !H.rt.links[p.n]?.up) continue;
      if (H.rt.addrs[p.n].some((a) => a.ip === ip)) return { hid: H.id, n: p.n };
    }
  }
  return null;
}

/**
 * Провести пакет от машины hid. inIf — входной интерфейс (null — пакет создан здесь).
 * pkt: { src, dst, dir: 'orig'|'reply', ct: [] — записи NAT по пути, fwd — сколько маршрутизаторов прошёл, hops?, inner? }
 */
export function send(hid, pkt, inIf, depth = 0) {
  const h = LAB.hosts[hid];
  const rt = h.rt;
  if (depth > 30) return { ok: false, why: 'loop', at: hid };

  if (ownAddr(h, pkt.dst)) {
    const k = pkt.dir === 'reply' ? pkt.ct.findIndex((c) => c.host === hid && c.nat === pkt.dst) : -1;
    if (k >= 0) {
      // Ответ на маскарадированный пакет: вернуть исходный адрес и вести дальше.
      pkt.dst = pkt.ct[k].orig;
      pkt.ct.splice(k, 1);
      return send(hid, pkt, inIf, depth + 1);
    }
    if (pkt.inner) {
      const t = Object.entries(rt.tun).find(([n, x]) => x.local === pkt.dst && x.remote === pkt.src && rt.links[n].up);
      if (!t) return { ok: false, why: 'gre', at: hid };
      return send(hid, pkt.inner, t[0], depth + 1);
    }
    if (inIf && filterDrops(h, 'INPUT', pkt, inIf, null)) return { ok: false, why: 'filtered', at: hid };
    return { ok: true, host: hid };
  }

  if (inIf !== null && !rt.fwd) return { ok: false, why: 'nofwd', at: hid };
  const r = lookupRoute(h, pkt.dst);
  if (!r) return { ok: false, why: inIf === null ? 'unreach' : 'noroute', at: hid };
  if (inIf === null && !pkt.src) {
    pkt.src = r.src;
    if (!pkt.src) return { ok: false, why: 'unreach', at: hid };
  }
  if (inIf !== null) {
    if (filterDrops(h, 'FORWARD', pkt, inIf, r.dev)) return { ok: false, why: 'filtered', at: hid };
    pkt.fwd = (pkt.fwd || 0) + 1;
    if (pkt.hops) pkt.hops.push(firstAddr(h, inIf) || '?');
  }
  if (pkt.dir === 'orig') {
    const rule = rt.ipt.nat.rules.find((x) => x.chain === 'POSTROUTING' && (x.j === 'MASQUERADE' || x.j === 'SNAT') && matchRule(x, pkt, null, r.dev, inNet));
    if (rule) {
      const ns = rule.j === 'SNAT' ? rule.to : firstAddr(h, r.dev);
      if (ns && ns !== pkt.src) {
        pkt.ct.push({ host: hid, orig: pkt.src, nat: ns });
        pkt.src = ns;
      }
    }
  }
  const tun = rt.tun[r.dev];
  if (tun) return send(hid, { src: tun.local, dst: tun.remote, dir: 'orig', ct: [], inner: pkt }, null, depth + 1);
  const p = h.phys.find((x) => x.n === r.dev);
  const nb = neighbor(p && p.seg, r.via || pkt.dst, hid);
  if (!nb) return { ok: false, why: inIf === null ? 'arp-origin' : 'arp', at: hid };
  return send(nb.hid, pkt, nb.n, depth + 1);
}

/** Пакет туда и ответ обратно. */
export function roundtrip(hid, dst, src = null) {
  const pkt = { src, dst, dir: 'orig', ct: [], fwd: 0, hops: [] };
  const f = send(hid, pkt, null);
  if (!f.ok) return { ...f, stage: 'fwd', src: pkt.src, hops: pkt.hops };
  const rp = { src: dst, dst: pkt.src, dir: 'reply', ct: pkt.ct.slice(), fwd: 0 };
  const b = send(f.host, rp, null);
  if (!b.ok) return { ...b, ok: false, stage: 'back', src: pkt.src, hops: pkt.hops };
  return { ok: true, ttl: 64 - (rp.fwd || 0), hops: pkt.hops, src: pkt.src };
}

/** Имя → адрес: /etc/hosts, затем DNS-серверы из /etc/resolv.conf. */
export function resolveName(h, name) {
  if (ip2n(name) !== null) return { ip: name };
  for (const l of lines(readIn(h.fs, '/etc/hosts') || '')) {
    const f = l.replace(/#.*$/, '').trim().split(/\s+/);
    if (f.length > 1 && f.slice(1).includes(name)) return { ip: f[0] };
  }
  const servers = lines(readIn(h.fs, '/etc/resolv.conf') || '')
    .map((l) => /^\s*nameserver\s+(\S+)/.exec(l))
    .filter(Boolean)
    .map((m) => m[1]);
  if (!servers.length) return { err: 'Temporary failure in name resolution', why: 'nons' };
  for (const n of servers) {
    if (!DNS_SERVERS.includes(n) || !roundtrip(h.id, n).ok) continue;
    const ip = DNS_ZONE[name];
    return ip ? { ip } : { err: 'Name or service not known' };
  }
  return { err: 'Temporary failure in name resolution', why: 'unreach' };
}
